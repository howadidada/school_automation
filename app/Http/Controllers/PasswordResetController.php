<?php

namespace App\Http\Controllers;

use App\Models\User;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Password;
use Illuminate\Support\Str;
use Illuminate\Validation\Rules\Password as PasswordRule;

class PasswordResetController extends Controller
{
    /**
     * عرض صفحة إعادة تعيين كلمة المرور.
     */
    public function show(Request $request, string $token)
    {
        $email = $request->query('email');

        /*
        |--------------------------------------------------------------------------
        | التحقق من البريد الإلكتروني
        |--------------------------------------------------------------------------
        */

        if (
            !is_string($email) ||
            !filter_var($email, FILTER_VALIDATE_EMAIL)
        ) {
            abort(403, 'رابط الاستعادة غير صالح.');
        }

        /*
        |--------------------------------------------------------------------------
        | البحث عن حساب المعلم
        |--------------------------------------------------------------------------
        */

        $user = User::query()
            ->where('email', $email)
            ->where('is_active', true)
            ->whereHas('teacher')
            ->first();

        /*
        |--------------------------------------------------------------------------
        | التحقق من صلاحية الرابط والحساب
        |--------------------------------------------------------------------------
        */

        if (
            !$user ||
            !$user->hasRole('teacher') ||
            $user->password === null ||
            !Password::broker()->tokenExists($user, $token)
        ) {
            abort(403, 'رابط الاستعادة غير صالح أو انتهت صلاحيته.');
        }

        /*
        |--------------------------------------------------------------------------
        | عرض صفحة إدخال كلمة المرور الجديدة
        |--------------------------------------------------------------------------
        */

        return view('auth.reset-password', [
            'token' => $token,
            'email' => $email,
        ]);
    }

    /**
     * حفظ كلمة المرور الجديدة.
     */
    public function reset(Request $request)
    {
        /*
        |--------------------------------------------------------------------------
        | التحقق من البيانات المدخلة
        |--------------------------------------------------------------------------
        */

        $validated = $request->validate([
            'token' => [
                'required',
                'string',
            ],
            'email' => [
                'required',
                'email',
            ],
            'password' => [
                'required',
                'confirmed',
                PasswordRule::min(8)
                    ->mixedCase()
                    ->numbers(),
            ],
        ]);

        /*
        |--------------------------------------------------------------------------
        | تنفيذ تغيير كلمة المرور داخل معاملة آمنة
        |--------------------------------------------------------------------------
        */

        $result = DB::transaction(function () use ($validated) {

            $user = User::query()
                ->where('email', $validated['email'])
                ->lockForUpdate()
                ->first();

            /*
            |--------------------------------------------------------------------------
            | التحقق من أهلية الحساب ورمز الاستعادة
            |--------------------------------------------------------------------------
            */

            if (
                !$user ||
                !$user->is_active ||
                !$user->hasRole('teacher') ||
                !$user->teacher ||
                $user->password === null ||
                !Password::broker()->tokenExists(
                    $user,
                    $validated['token']
                )
            ) {
                return false;
            }

            /*
            |--------------------------------------------------------------------------
            | تحديث كلمة المرور
            |--------------------------------------------------------------------------
            |
            | يتم تشفير كلمة المرور تلقائيًا بواسطة
            | hashed cast الموجود في User.
            |
            */

            $user->forceFill([
                'password' => $validated['password'],
                'remember_token' => Str::random(60),
            ])->save();

            /*
            |--------------------------------------------------------------------------
            | إلغاء جميع رموز دخول التطبيق السابقة
            |--------------------------------------------------------------------------
            */

            $user->tokens()->delete();

            /*
            |--------------------------------------------------------------------------
            | حذف رمز الاستعادة بعد استخدامه
            |--------------------------------------------------------------------------
            */

            Password::broker()->deleteToken($user);

            return true;

        }, 3);

        /*
        |--------------------------------------------------------------------------
        | التعامل مع رابط غير صالح
        |--------------------------------------------------------------------------
        */

        if (!$result) {
            return back()->withErrors([
                'email' => 'رابط الاستعادة غير صالح أو انتهت صلاحيته.',
            ]);
        }

        /*
        |--------------------------------------------------------------------------
        | الانتقال إلى صفحة النجاح
        |--------------------------------------------------------------------------
        */

        return redirect()
            ->route('password.reset.success');
    }

    /**
     * عرض صفحة نجاح إعادة تعيين كلمة المرور.
     */
    public function success()
    {
        return view('auth.password-reset-success');
    }
}