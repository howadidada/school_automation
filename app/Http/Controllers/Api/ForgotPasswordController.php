<?php

namespace App\Http\Controllers\Api;

use App\Http\Controllers\Controller;
use App\Models\User;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\Log;
use Illuminate\Support\Facades\Mail;
use Illuminate\Support\Facades\Password;
use Illuminate\Support\Facades\RateLimiter;
use Throwable;

class ForgotPasswordController extends Controller
{
    /**
     * استقبال طلب استعادة كلمة المرور من Flutter.
     */
    public function sendResetLink(Request $request)
    {
        $validated = $request->validate([
            'email' => [
                'required',
                'email',
                'max:255',
            ],
        ]);

        /*
        |--------------------------------------------------------------------------
        | رسالة موحدة لحماية خصوصية الحسابات
        |--------------------------------------------------------------------------
        */

        $message = 'إذا كان البريد الإلكتروني مرتبطًا بحساب مؤهل '
            . 'في نظام صلة، فستصلك رسالة تحتوي على رابط '
            . 'إعادة تعيين كلمة المرور.';

        /*
        |--------------------------------------------------------------------------
        | توحيد البريد الإلكتروني
        |--------------------------------------------------------------------------
        */

        $email = trim($validated['email']);

        /*
        |--------------------------------------------------------------------------
        | البحث عن حساب معلم نشط
        |--------------------------------------------------------------------------
        */

        $user = User::query()
            ->where('email', $email)
            ->where('is_active', true)
            ->whereHas('teacher')
            ->first();

        /*
        |--------------------------------------------------------------------------
        | التحقق من أهلية الحساب
        |--------------------------------------------------------------------------
        |
        | لا يُرسل رابط استعادة للحسابات غير المفعلة.
        | الحساب غير المفعل يستخدم رابط التفعيل الأصلي.
        |
        */

        if (
            !$user ||
            !$user->hasRole('teacher') ||
            $user->password === null
        ) {
            return response()->json([
                'success' => true,
                'message' => $message,
            ]);
        }

        /*
        |--------------------------------------------------------------------------
        | الحد من تكرار إرسال الرسائل
        |--------------------------------------------------------------------------
        |
        | طلب واحد لكل حساب خلال 60 ثانية.
        | إعادة الطلب خلال هذه الفترة تعطي نفس الاستجابة.
        |
        */

        $rateLimitKey = 'password-reset-email:' . $user->id;

        if (RateLimiter::tooManyAttempts($rateLimitKey, 1)) {
            return response()->json([
                'success' => true,
                'message' => $message,
            ]);
        }

        /*
        |--------------------------------------------------------------------------
        | إنشاء رمز استعادة كلمة المرور
        |--------------------------------------------------------------------------
        */

        try {

            $token = Password::broker()->createToken($user);

            /*
            |--------------------------------------------------------------------------
            | إنشاء رابط الاستعادة باستخدام عنوان ثابت
            |--------------------------------------------------------------------------
            |
            | نقرأ عنوان روابط البريد من config/sila.php.
            |
            | لا نستخدم عنوان الطلب القادم من Flutter،
            | حتى لا يظهر عنوان المحاكي 10.0.2.2.
            |
            */

            $baseUrl = rtrim(
                (string) config(
                    'sila.mail_link_base_url',
                    config('app.url')
                ),
                '/'
            );

            /*
            |--------------------------------------------------------------------------
            | إنشاء المسار النسبي لرابط الاستعادة
            |--------------------------------------------------------------------------
            |
            | false تمنع Laravel من إضافة عنوان السيرفر.
            |
            */

            $resetPath = route(
                'password.reset.form',
                [
                    'token' => $token,
                    'email' => $user->email,
                ],
                false
            );

            /*
            |--------------------------------------------------------------------------
            | إنشاء الرابط الكامل
            |--------------------------------------------------------------------------
            */

            $resetUrl = $baseUrl . $resetPath;

            /*
            |--------------------------------------------------------------------------
            | إرسال رسالة استعادة كلمة المرور
            |--------------------------------------------------------------------------
            */

            Mail::send(
                'emails.password-reset',
                [
                    'user' => $user,
                    'resetUrl' => $resetUrl,
                ],
                function ($mail) use ($user) {

                    $mail
                        ->to($user->email)
                        ->subject(
                            'استعادة كلمة المرور - نظام صلة'
                        );

                }
            );

            /*
            |--------------------------------------------------------------------------
            | تسجيل نجاح الإرسال في محدد الطلبات
            |--------------------------------------------------------------------------
            */

            RateLimiter::hit($rateLimitKey, 60);

        } catch (Throwable $exception) {

            /*
            |--------------------------------------------------------------------------
            | تسجيل الخطأ دون كشف تفاصيل الحساب
            |--------------------------------------------------------------------------
            */

            Log::error('Password reset email failed.', [
                'user_id' => $user->id,
                'exception' => $exception,
            ]);

        }

        /*
        |--------------------------------------------------------------------------
        | استجابة موحدة
        |--------------------------------------------------------------------------
        */

        return response()->json([
            'success' => true,
            'message' => $message,
        ]);
    }
}